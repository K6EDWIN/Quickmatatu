BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
  migration_id TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_type TEXT NOT NULL CHECK (user_type IN ('commuter', 'driver')),
  username TEXT,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  license_number TEXT,
  id_number TEXT,
  driver_name TEXT,
  vehicle_license_plate TEXT,
  auth_version BIGINT NOT NULL DEFAULT 0 CHECK (auth_version >= 0),
  email_verified SMALLINT NOT NULL DEFAULT 0 CHECK (email_verified IN (0, 1)),
  google_sub TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS routes (
  route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_name TEXT,
  start_point TEXT,
  end_point TEXT,
  intermediary_stops TEXT,
  estimated_duration TEXT,
  longitude DOUBLE PRECISION,
  latitude DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tickets (
  ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  commuter_id BIGINT NOT NULL REFERENCES users(user_id),
  route_id BIGINT NOT NULL REFERENCES routes(route_id),
  pickup_point TEXT NOT NULL,
  booking_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'accepted', 'rejected', 'cancelled', 'completed')),
  driver_id BIGINT REFERENCES users(user_id)
);

CREATE TABLE IF NOT EXISTS active_drivers (
  driver_id BIGINT PRIMARY KEY REFERENCES users(user_id),
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  last_updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auth_challenges (
  challenge_id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(user_id),
  purpose TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
  code_hash TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  expires_at BIGINT NOT NULL,
  consumed_at BIGINT,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS google_auth_nonces (
  nonce_hash TEXT PRIMARY KEY,
  expires_at BIGINT NOT NULL,
  consumed_at BIGINT,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_rate_limits (
  action TEXT NOT NULL,
  key_hash TEXT NOT NULL,
  window_started_at BIGINT NOT NULL,
  attempts INTEGER NOT NULL CHECK (attempts > 0),
  PRIMARY KEY (action, key_hash)
);

CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub_unique
  ON users (google_sub) WHERE google_sub IS NOT NULL;
CREATE INDEX IF NOT EXISTS auth_challenges_user_purpose_created
  ON auth_challenges (user_id, purpose, created_at DESC);
CREATE INDEX IF NOT EXISTS tickets_commuter_booking_time
  ON tickets (commuter_id, booking_time DESC);
CREATE INDEX IF NOT EXISTS tickets_driver_booking_time
  ON tickets (driver_id, booking_time DESC);
CREATE INDEX IF NOT EXISTS tickets_pending_unassigned
  ON tickets (booking_time ASC) WHERE status = 'pending' AND driver_id IS NULL;
CREATE INDEX IF NOT EXISTS active_drivers_active_updated
  ON active_drivers (last_updated DESC) WHERE is_active = TRUE;
CREATE INDEX IF NOT EXISTS routes_name
  ON routes (route_name);

INSERT INTO schema_migrations (migration_id)
VALUES ('20261118_neon_initial')
ON CONFLICT (migration_id) DO NOTHING;

COMMIT;
